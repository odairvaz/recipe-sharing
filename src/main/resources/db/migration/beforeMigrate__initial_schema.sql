-- Flyway callback (runs before every migrate).
--
-- The original schema was created by Hibernate (ddl-auto=update), and V1 is only an empty baseline marker,
-- so a brand-new database had no tables for V2/V3 to act on. This idempotent script creates the schema
-- the entities expect when it is missing, and is a no-op on databases that already have it.
-- Put future schema changes in regular versioned migrations (V4__..., V5__...).

CREATE TABLE IF NOT EXISTS users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(255),
    last_name   VARCHAR(255),
    email       VARCHAR(255),
    password    VARCHAR(255),
    bio         TEXT,
    avatar_url  VARCHAR(255),
    created_at  TIMESTAMP(6),
    enabled     BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS recipe (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(255),
    description  VARCHAR(255),
    ingredients  TEXT,
    instructions TEXT,
    category     VARCHAR(255),
    image_url    VARCHAR(255),
    user_id      BIGINT NOT NULL REFERENCES users (id),
    created_at   TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS reviews (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id  BIGINT  NOT NULL REFERENCES recipe (id),
    user_id    BIGINT  NOT NULL REFERENCES users (id),
    rating     INTEGER NOT NULL,
    comment    VARCHAR(255),
    created_at TIMESTAMP(6),
    CONSTRAINT uk_reviews_user_recipe UNIQUE (user_id, recipe_id)
);

CREATE TABLE IF NOT EXISTS favorites (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id  BIGINT NOT NULL REFERENCES recipe (id),
    user_id    BIGINT NOT NULL REFERENCES users (id),
    created_at TIMESTAMP(6),
    CONSTRAINT uk_favorites_user_recipe UNIQUE (user_id, recipe_id)
);

CREATE TABLE IF NOT EXISTS verification_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token       VARCHAR(255),
    user_id     BIGINT NOT NULL UNIQUE REFERENCES users (id),
    expiry_date TIMESTAMP(6)
);
